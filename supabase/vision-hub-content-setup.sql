-- Media uploaded here must be owned by you or licensed for public display.
create table if not exists public.vh_content (
  id bigint generated by default as identity primary key,
  title text not null,
  content_type text not null check (content_type in ('Movie','Web Series','Documentary','Short')),
  video_url text not null,
  poster_url text,
  genre text,
  language text,
  release_year integer,
  rating numeric(3,1),
  description text,
  cast text,
  duration text,
  trailer_url text,
  industry text,
  published boolean not null default false,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);
alter table public.vh_content enable row level security;
drop policy if exists "Public can read published content" on public.vh_content;
create policy "Public can read published content" on public.vh_content
  for select using (published = true);
drop policy if exists "Admins can manage content" on public.vh_content;
create policy "Admins can manage content" on public.vh_content
  for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

insert into storage.buckets (id, name, public)
values ('vh-media', 'vh-media', true)
on conflict (id) do update set public = true;

drop policy if exists "Public can view published media" on storage.objects;
create policy "Public can view published media" on storage.objects
  for select using (bucket_id = 'vh-media');
drop policy if exists "Admins can upload media" on storage.objects;
create policy "Admins can upload media" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'vh-media' and exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  ));
drop policy if exists "Admins can update media" on storage.objects;
create policy "Admins can update media" on storage.objects
  for update to authenticated
  using (bucket_id = 'vh-media' and exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  ))
  with check (bucket_id = 'vh-media' and exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  ));
drop policy if exists "Admins can delete media" on storage.objects;
create policy "Admins can delete media" on storage.objects
  for delete to authenticated
  using (bucket_id = 'vh-media' and exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  ));
