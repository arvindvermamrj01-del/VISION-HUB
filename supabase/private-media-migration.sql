-- Vision Hub private media migration (existing Supabase projects)
-- Run in Supabase SQL Editor as project owner before deploying code that uploads to vh-private-media.
-- Existing public vh-media objects are intentionally left untouched for compatibility.
-- Run sub-admin-role-migration.sql first so vh_can_manage_content_item() exists.

alter table public.vh_content add column if not exists storage_path text;
alter table public.vh_content add column if not exists storage_provider text not null default 'supabase';

create table if not exists public.vh_media_assets (
  id bigint generated by default as identity primary key,
  content_id bigint not null references public.vh_content(id) on delete cascade,
  asset_type text not null check (asset_type in ('video','audio','subtitle')),
  resolution text check (resolution is null or resolution in ('180p','240p','420p','480p','720p','1080p','2k','4k','8k')),
  language text not null default 'Original',
  label text,
  asset_url text not null default '',
  storage_path text,
  storage_provider text not null default 'supabase',
  mime_type text,
  file_size_bytes bigint check (file_size_bytes is null or file_size_bytes >= 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint vh_media_asset_resolution_type check ((asset_type='video' and resolution is not null) or (asset_type<>'video' and resolution is null))
);
alter table public.vh_media_assets add column if not exists storage_path text;
alter table public.vh_media_assets add column if not exists storage_provider text not null default 'supabase';
alter table public.vh_media_assets add column if not exists asset_url text not null default '';
alter table public.vh_media_assets enable row level security;
drop policy if exists "published media tracks readable" on public.vh_media_assets;
create policy "published media tracks readable" on public.vh_media_assets for select to anon, authenticated
using (exists(select 1 from public.vh_content c where c.id=content_id and c.published=true) or public.vh_is_admin());
drop policy if exists "main admins manage media tracks" on public.vh_media_assets;
create policy "main admins manage media tracks" on public.vh_media_assets for all to authenticated
using (public.vh_is_admin()) with check (public.vh_is_admin());
grant select on public.vh_media_assets to anon, authenticated;
grant insert, update, delete on public.vh_media_assets to authenticated;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('vh-private-media','vh-private-media',false,1073741824,array[
 'video/mp4','video/webm','video/quicktime','video/x-m4v',
 'audio/mpeg','audio/mp4','audio/aac','audio/ogg','audio/wav','text/vtt'
])
on conflict (id) do update set public=false, file_size_limit=excluded.file_size_limit, allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists "published private media signed read" on storage.objects;
create policy "published private media signed read" on storage.objects for select to anon, authenticated
using (
  bucket_id='vh-private-media' and (
    public.vh_is_admin()
    or exists(select 1 from public.vh_content c where c.storage_path=storage.objects.name and c.published=true)
    or exists(select 1 from public.vh_media_assets a join public.vh_content c on c.id=a.content_id
              where a.storage_path=storage.objects.name and a.storage_provider='supabase' and c.published=true)
  )
);

drop policy if exists "admins upload private media" on storage.objects;
drop policy if exists "staff upload private media" on storage.objects;
create policy "staff upload private media" on storage.objects for insert to authenticated
with check (bucket_id='vh-private-media' and (storage.foldername(name))[1]=auth.uid()::text and public.vh_can_manage_content());

drop policy if exists "admins delete private media" on storage.objects;
drop policy if exists "staff delete linked private media" on storage.objects;
create policy "staff delete linked private media" on storage.objects for delete to authenticated
using (
  bucket_id='vh-private-media' and (
    public.vh_is_admin()
    or exists(select 1 from public.vh_content c
              where c.storage_path=storage.objects.name
              and public.vh_can_manage_content_item(c.content_type))
    or exists(select 1 from public.vh_media_assets a join public.vh_content c on c.id=a.content_id
              where a.storage_path=storage.objects.name
              and a.storage_provider='supabase'
              and public.vh_can_manage_content_item(c.content_type))
  )
);
