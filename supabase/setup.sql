create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  fullname text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create or replace function public.vh_is_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin');
$$;
revoke all on function public.vh_is_admin() from public;
grant execute on function public.vh_is_admin() to authenticated;

create or replace function public.vh_create_profile()
returns trigger language plpgsql security definer
set search_path = public
as $$
begin
  insert into public.profiles(id, fullname)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'fullname', split_part(new.email,'@',1)))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists vh_auth_user_created on auth.users;
create trigger vh_auth_user_created after insert on auth.users
for each row execute procedure public.vh_create_profile();

drop policy if exists "profile read self or admin" on public.profiles;
create policy "profile read self or admin" on public.profiles for select to authenticated
using (id = auth.uid() or public.vh_is_admin());
drop policy if exists "profile update self name only" on public.profiles;
create policy "profile update self name only" on public.profiles for update to authenticated
using (id = auth.uid() or public.vh_is_admin())
with check (id = auth.uid() or public.vh_is_admin());
-- Do not grant authenticated users direct insert/update access to role.
revoke insert, update, delete on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update(fullname) on public.profiles to authenticated;

