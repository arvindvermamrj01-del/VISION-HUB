create table if not exists public.vh_idea_votes (
  id bigint generated by default as identity primary key,
  idea_id bigint not null references public.vh_ideas(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (idea_id,user_id)
);
alter table public.vh_idea_votes enable row level security;
drop policy if exists "users vote once" on public.vh_idea_votes;
create policy "users vote once" on public.vh_idea_votes for insert to authenticated
with check (
  user_id = auth.uid()
  and exists (
    select 1 from public.vh_ideas i
    where i.id = vh_idea_votes.idea_id and i.status <> 'declined'
  )
);
drop policy if exists "admins read votes" on public.vh_idea_votes;
create policy "admins read votes" on public.vh_idea_votes for select to authenticated using (public.vh_is_admin());
grant insert on public.vh_idea_votes to authenticated;
grant select on public.vh_idea_votes to authenticated;

create or replace function public.vh_increment_idea_vote()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  update public.vh_ideas set vote_count=vote_count+1 where id=new.idea_id;
  return new;
end;
$$;
drop trigger if exists vh_idea_vote_count on public.vh_idea_votes;
create trigger vh_idea_vote_count after insert on public.vh_idea_votes
for each row execute procedure public.vh_increment_idea_vote();
revoke all on function public.vh_increment_idea_vote() from public;

