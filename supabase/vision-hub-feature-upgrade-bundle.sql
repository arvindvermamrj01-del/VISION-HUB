-- ===== supabase/vision-hub-donations.sql =====
-- VISION HUB donations: UPI confirmations are pending until an administrator verifies them.
-- This records user-submitted references; it does NOT claim automatic payment verification.

create table if not exists public.vh_donations (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  donor_name text not null check (char_length(btrim(donor_name)) between 1 and 80),
  amount numeric(10,2) not null check (amount >= 1 and amount <= 100000),
  currency text not null default 'INR' check (currency = 'INR'),
  payment_reference text not null check (payment_reference ~ '^[A-Za-z0-9-]{8,64}$'),
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  verified_by uuid references auth.users(id) on delete set null
);

create unique index if not exists vh_donations_reference_unique
  on public.vh_donations (lower(payment_reference));
create index if not exists vh_donations_created_at_idx
  on public.vh_donations (created_at desc);
create index if not exists vh_donations_user_id_idx
  on public.vh_donations (user_id);

alter table public.vh_donations enable row level security;
revoke all on public.vh_donations from anon, authenticated;
grant insert on public.vh_donations to anon, authenticated;
grant select, update on public.vh_donations to authenticated;
grant usage, select on sequence public.vh_donations_id_seq to anon, authenticated;

drop policy if exists "vh_donations_public_submit" on public.vh_donations;
create policy "vh_donations_public_submit" on public.vh_donations
  for insert to anon, authenticated
  with check (
    status = 'pending'
    and verified_at is null
    and verified_by is null
    and (user_id is null or user_id = (select auth.uid()))
  );

drop policy if exists "vh_donations_owner_or_admin_read" on public.vh_donations;
create policy "vh_donations_owner_or_admin_read" on public.vh_donations
  for select to authenticated
  using (user_id = (select auth.uid()) or public.vh_is_admin());

drop policy if exists "vh_donations_admin_update" on public.vh_donations;
create policy "vh_donations_admin_update" on public.vh_donations
  for update to authenticated
  using (public.vh_is_admin())
  with check (public.vh_is_admin());


-- ===== supabase/vision-hub-series-episodes.sql =====
-- VISION HUB series seasons and episodes.
-- Episodes are catalog rows so existing private-media signing, watch progress and player quality code can be reused.

alter table public.vh_content
  add column if not exists parent_series_id bigint references public.vh_content(id) on delete cascade,
  add column if not exists season_number integer,
  add column if not exists episode_number integer;

do $$
declare c record;
begin
  for c in
    select conname
    from pg_constraint
    where conrelid='public.vh_content'::regclass
      and contype='c'
      and pg_get_constraintdef(oid) ilike '%content_type%'
  loop
    execute format('alter table public.vh_content drop constraint %I',c.conname);
  end loop;
end $$;

alter table public.vh_content
  add constraint vh_content_content_type_check
  check (content_type in ('Movie','Web Series','Documentary','Short','Episode'));

alter table public.vh_content
  drop constraint if exists vh_content_episode_metadata_check;
alter table public.vh_content
  add constraint vh_content_episode_metadata_check
  check (
    content_type <> 'Episode'
    or (parent_series_id is not null and season_number >= 1 and episode_number >= 1)
  );

create unique index if not exists vh_content_series_episode_unique
  on public.vh_content(parent_series_id,season_number,episode_number)
  where content_type='Episode';
create index if not exists vh_content_series_episode_order_idx
  on public.vh_content(parent_series_id,season_number,episode_number)
  where content_type='Episode';

-- Episode uploads use the same private providers and may also use authorised external URLs.
alter table public.vh_content
  drop constraint if exists vh_content_storage_provider_check;
alter table public.vh_content
  add constraint vh_content_storage_provider_check
  check (storage_provider in (
    'supabase','cloudflare_r2','backblaze_b2','terabox','mega','degoo',
    'google_drive','mediafire','pcloud','box','icedrive','koofr','internxt','telegram','direct'
  ));

alter table public.vh_media_assets
  drop constraint if exists vh_media_assets_storage_provider_check;
alter table public.vh_media_assets
  add constraint vh_media_assets_storage_provider_check
  check (storage_provider in (
    'supabase','cloudflare_r2','backblaze_b2','terabox','mega','degoo',
    'google_drive','mediafire','pcloud','box','icedrive','koofr','internxt','telegram','direct'
  ));

commit;
