-- ===== Community feedback and authenticated voting =====
-- VISION HUB community feedback, feature requests and authenticated voting.

create table if not exists public.vh_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('suggestion','bug','complaint')),
  title text not null check (char_length(btrim(title)) between 4 and 120),
  description text not null check (char_length(btrim(description)) between 10 and 3000),
  status text not null default 'pending' check (status in ('pending','under_review','planned','in_progress','completed','declined')),
  admin_response text,
  upvotes integer not null default 0 check (upvotes >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vh_feedback_votes (
  id bigint generated by default as identity primary key,
  feedback_id bigint not null references public.vh_feedback(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(feedback_id,user_id)
);

create index if not exists vh_feedback_status_votes_idx on public.vh_feedback(status,upvotes desc,created_at desc);
create index if not exists vh_feedback_user_created_idx on public.vh_feedback(user_id,created_at desc);

alter table public.vh_feedback enable row level security;
alter table public.vh_feedback_votes enable row level security;
revoke all on public.vh_feedback from anon,authenticated;
revoke all on public.vh_feedback_votes from anon,authenticated;
grant select on public.vh_feedback to anon;
grant select,insert,update on public.vh_feedback to authenticated;
grant select on public.vh_feedback_votes to authenticated;
grant usage,select on sequence public.vh_feedback_id_seq,public.vh_feedback_votes_id_seq to authenticated;

drop policy if exists "vh_feedback_public_board" on public.vh_feedback;
create policy "vh_feedback_public_board" on public.vh_feedback
  for select to anon,authenticated
  using (status in ('planned','in_progress','completed'));

drop policy if exists "vh_feedback_owner_read" on public.vh_feedback;
create policy "vh_feedback_owner_read" on public.vh_feedback
  for select to authenticated using (user_id=(select auth.uid()));

drop policy if exists "vh_feedback_admin_read" on public.vh_feedback;
create policy "vh_feedback_admin_read" on public.vh_feedback
  for select to authenticated using (public.vh_is_admin());

drop policy if exists "vh_feedback_authenticated_submit" on public.vh_feedback;
create policy "vh_feedback_authenticated_submit" on public.vh_feedback
  for insert to authenticated
  with check (user_id=(select auth.uid()) and status='pending' and upvotes=0);

drop policy if exists "vh_feedback_admin_update" on public.vh_feedback;
create policy "vh_feedback_admin_update" on public.vh_feedback
  for update to authenticated
  using (public.vh_is_admin())
  with check (public.vh_is_admin());

drop policy if exists "vh_feedback_votes_owner_read" on public.vh_feedback_votes;
create policy "vh_feedback_votes_owner_read" on public.vh_feedback_votes
  for select to authenticated using (user_id=(select auth.uid()));

drop policy if exists "vh_feedback_votes_owner_insert" on public.vh_feedback_votes;
create policy "vh_feedback_votes_owner_insert" on public.vh_feedback_votes
  for insert to authenticated with check (user_id=(select auth.uid()));

create or replace function public.vh_vote_feedback(p_feedback_id bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_inserted bigint;
  v_votes integer;
begin
  if v_user is null then
    raise exception 'Sign in to vote.';
  end if;
  insert into public.vh_feedback_votes(feedback_id,user_id)
  select f.id,v_user
  from public.vh_feedback f
  where f.id=p_feedback_id and f.status in ('planned','in_progress','completed')
  on conflict (feedback_id,user_id) do nothing
  returning id into v_inserted;

  if v_inserted is not null then
    update public.vh_feedback
      set upvotes=upvotes+1,updated_at=now()
      where id=p_feedback_id;
  end if;

  select upvotes into v_votes from public.vh_feedback where id=p_feedback_id;
  if v_votes is null then raise exception 'Feedback item not found.'; end if;
  return v_votes;
end;
$$;

revoke all on function public.vh_vote_feedback(bigint) from public;
grant execute on function public.vh_vote_feedback(bigint) to authenticated;



